INSERT INTO SUN5_INRIKTNING (
    SUN5_KOD,
    UTBILDNINGSOMRADE_ID,
    SUN5_NAME
)
SELECT DISTINCT
    y.SUN5_INRIKTNING,
    u.UTBILDNINGSOMRADE_ID,
    y.SUN5_INRIKTNING_NAMN
FROM YH_APPLICATIONS_2025 y
JOIN UTBILDNINGSOMRADE u
    ON y.UTBILDNINGSOMRADE = u.UTBILDNINGSOMRADE_NAME
WHERE y.SUN5_INRIKTNING IS NOT NULL
	AND NOT EXISTS (
		SELECT 1
		FROM SUN5_INRIKTNING s
		WHERE s.SUN5_KOD = y.SUN5_INRIKTNING
);
COMMIT;

SELECT COUNT(*) AS ANTAL_INRIKTNINGAR
FROM SUN5_INRIKTNING;
