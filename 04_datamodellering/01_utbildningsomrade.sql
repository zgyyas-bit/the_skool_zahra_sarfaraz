-- Uppgift 4 - Tabell 1
-- Skapa tabellen endast om den inte redan finns

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE UTBILDNINGSOMRADE (
            UTBILDNINGSOMRADE_ID NUMBER
                GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            UTBILDNINGSOMRADE_NAME VARCHAR2(150) NOT NULL UNIQUE
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN
            RAISE;
        END IF;
END;
/

-- Importera endast utbildningsomraden som saknas

MERGE INTO UTBILDNINGSOMRADE u
USING (
    SELECT DISTINCT UTBILDNINGSOMRADE AS NAMN
    FROM YH_APPLICATIONS_2025
    WHERE UTBILDNINGSOMRADE IS NOT NULL
) y
ON (u.UTBILDNINGSOMRADE_NAME = y.NAMN)

WHEN NOT MATCHED THEN
    INSERT (UTBILDNINGSOMRADE_NAME)
    VALUES (y.NAMN);

COMMIT;

-- Visa alla utbildningsomraden

SELECT *
FROM UTBILDNINGSOMRADE
ORDER BY UTBILDNINGSOMRADE_ID;
