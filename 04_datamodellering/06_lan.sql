-- Uppgift 4 - Tabell 6
-- Skapa och fyll tabellen LAN

SET SQLBLANKLINES ON

-- Skapa tabellen om den inte redan finns
BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE LAN (
            LAN_ID NUMBER
                GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            LAN_NAME VARCHAR2(100 CHAR) NOT NULL UNIQUE
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN
            RAISE;
        END IF;
END;
/

-- Importera endast lan som saknas
-- Exkludera Flera kommuner eftersom det inte ar ett lan

MERGE INTO LAN l
USING (
    SELECT DISTINCT LAN AS LAN_NAME
    FROM YH_APPLICATIONS_2025
    WHERE LAN IS NOT NULL
      AND LAN <> 'Flera kommuner'
) y
ON (l.LAN_NAME = y.LAN_NAME)
WHEN NOT MATCHED THEN
    INSERT (LAN_NAME)
    VALUES (y.LAN_NAME);

COMMIT;

-- Kontrollera antal lan
SELECT COUNT(*) AS ANTAL_LAN
FROM LAN;

-- Visa alla lan
SELECT *
FROM LAN
ORDER BY LAN_NAME;
