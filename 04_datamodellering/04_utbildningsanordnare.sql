-- Skapa tabellen UTBILDNINGSANORDNARE
-- Skapa tabellen om den inte redan finns

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE UTBILDNINGSANORDNARE (
            ANORDNARE_ID NUMBER
                GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            NAMN VARCHAR2(255 CHAR) NOT NULL UNIQUE,
            HUVUDMANNATYP VARCHAR2(50 CHAR)
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN
            RAISE;
        END IF;
END;
/

-- Importera bara anordnare som inte redan finns

MERGE INTO UTBILDNINGSANORDNARE a
USING (
    SELECT
        UTBILDNINGSANORDNARE_ADMINISTR AS NAMN,
        MAX(HUVUDMANNATYP) AS HUVUDMANNATYP
    FROM YH_APPLICATIONS_2025
    WHERE UTBILDNINGSANORDNARE_ADMINISTR IS NOT NULL
    GROUP BY UTBILDNINGSANORDNARE_ADMINISTR
) y

ON (a.NAMN = y.NAMN)

WHEN NOT MATCHED THEN
    INSERT (NAMN, HUVUDMANNATYP)
    VALUES (y.NAMN, y.HUVUDMANNATYP);

COMMIT;

-- Kontrollera antalet anordnare

SELECT COUNT(*) AS ANTAL_ANORDNARE
FROM UTBILDNINGSANORDNARE;

-- Visa anordnare och huvudmannatyp

SELECT
    ANORDNARE_ID,
    NAMN,
    HUVUDMANNATYP
FROM UTBILDNINGSANORDNARE
ORDER BY NAMN;

