-- Antal beviljade ansokningar per utbildningsnamn inom Data/IT
-- Anvander den nya datamodellen med JOIN

SELECT
    a.UTBILDNINGSNAMN,
    COUNT(*) AS ANTAL_BEVILJADE
FROM ANSOKAN a
JOIN SUN5_INRIKTNING s
    ON a.SUN5_KOD = s.SUN5_KOD
JOIN UTBILDNINGSOMRADE u
    ON s.UTBILDNINGSOMRADE_ID = u.UTBILDNINGSOMRADE_ID
WHERE u.UTBILDNINGSOMRADE_NAME = 'Data/IT'
  AND a.BESLUT = 'Beviljad'
GROUP BY a.UTBILDNINGSNAMN
ORDER BY ANTAL_BEVILJADE DESC, a.UTBILDNINGSNAMN;
