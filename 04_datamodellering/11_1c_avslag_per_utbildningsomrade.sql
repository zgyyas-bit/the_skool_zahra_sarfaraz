-- Antal avslagna ansokningar per utbildningsomrade
-- Nya datamodellen

SELECT
    u.UTBILDNINGSOMRADE_NAME AS UTBILDNINGSOMRADE,
    COUNT(*) AS ANTAL_AVSLAGNA
FROM ANSOKAN a
JOIN SUN5_INRIKTNING s
    ON a.SUN5_KOD = s.SUN5_KOD
JOIN UTBILDNINGSOMRADE u
    ON s.UTBILDNINGSOMRADE_ID = u.UTBILDNINGSOMRADE_ID
WHERE a.BESLUT = 'Avslag'
GROUP BY u.UTBILDNINGSOMRADE_NAME
ORDER BY ANTAL_AVSLAGNA DESC;
