-- Uppgift 4 - Tabell 5
-- Skapa ANSOKAN enligt lararens datamodell

SET SQLBLANKLINES ON

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE ANSOKAN (
            DIARIENUMMER VARCHAR2(26) PRIMARY KEY,
            SUN5_KOD VARCHAR2(26) NOT NULL,
            SEQF_KOD NUMBER(3),
            ANORDNARE_ID NUMBER NOT NULL,
            UTBILDNINGSNAMN VARCHAR2(128),
            BESLUT VARCHAR2(26),
            YH_POANG NUMBER(5),
            STUDIEFORM VARCHAR2(26),
            STUDIETAKT_PROCENT NUMBER(5),
            SMALT_YRKESOMRADE VARCHAR2(26),
            SOKTA_UTBILDNINGSOMGANGAR NUMBER(3),
            BEVILJADE_UTBILDNINGSOMGANGAR NUMBER(3),
            SOKTA_PLATSER_TOTALT NUMBER(5),
            BEVILJADE_PLATSER_TOTALT NUMBER(5),

            CONSTRAINT FK_ANSOKAN_SUN5
                FOREIGN KEY (SUN5_KOD)
                REFERENCES SUN5_INRIKTNING(SUN5_KOD),

            CONSTRAINT FK_ANSOKAN_SEQF
                FOREIGN KEY (SEQF_KOD)
                REFERENCES SEQF(SEQF_KOD),

            CONSTRAINT FK_ANSOKAN_ANORDNARE
                FOREIGN KEY (ANORDNARE_ID)
                REFERENCES UTBILDNINGSANORDNARE(ANORDNARE_ID)
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN
            RAISE;
        END IF;
END;
/

-- Importera ansokningar som inte redan finns

MERGE INTO ANSOKAN a
USING (
    SELECT
        y.DIARIENUMMER,
        y.SUN5_INRIKTNING AS SUN5_KOD,
        y.SEQF_NIVA AS SEQF_KOD,
        u.ANORDNARE_ID,
        y.UTBILDNINGSNAMN,
        y.BESLUT,
        y.YH_POANG,
        y.STUDIEFORM,
        y.STUDIETAKT AS STUDIETAKT_PROCENT,
        y.SMALT_YRKESOMRADE,
        y.SOKTA_UTBILDNINGSOMGANGAR,
        y.BEVILJADE_UTBILDNINGSOMGANGAR,
        y.SOKTA_PLATSER_TOTALT,
        y.BEVILJADE_PLATSER_TOTALT
    FROM YH_APPLICATIONS_2025 y
    JOIN UTBILDNINGSANORDNARE u
        ON y.UTBILDNINGSANORDNARE_ADMINISTR = u.NAMN
) k
ON (a.DIARIENUMMER = k.DIARIENUMMER)
WHEN NOT MATCHED THEN
    INSERT (
        DIARIENUMMER,
        SUN5_KOD,
        SEQF_KOD,
        ANORDNARE_ID,
        UTBILDNINGSNAMN,
        BESLUT,
        YH_POANG,
        STUDIEFORM,
        STUDIETAKT_PROCENT,
        SMALT_YRKESOMRADE,
        SOKTA_UTBILDNINGSOMGANGAR,
        BEVILJADE_UTBILDNINGSOMGANGAR,
        SOKTA_PLATSER_TOTALT,
        BEVILJADE_PLATSER_TOTALT
    )
    VALUES (
        k.DIARIENUMMER,
        k.SUN5_KOD,
        k.SEQF_KOD,
        k.ANORDNARE_ID,
        k.UTBILDNINGSNAMN,
        k.BESLUT,
        k.YH_POANG,
        k.STUDIEFORM,
        k.STUDIETAKT_PROCENT,
        k.SMALT_YRKESOMRADE,
        k.SOKTA_UTBILDNINGSOMGANGAR,
        k.BEVILJADE_UTBILDNINGSOMGANGAR,
        k.SOKTA_PLATSER_TOTALT,
        k.BEVILJADE_PLATSER_TOTALT
    );

COMMIT;

-- Kontrollera antalet ansokningar

SELECT COUNT(*) AS ANTAL_ANSOKNINGAR
FROM ANSOKAN;
