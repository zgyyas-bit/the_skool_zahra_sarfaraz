-- Uppgift 4 - Tabell 7 KOMMUN

SET SQLBLANKLINES ON

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE KOMMUN (
            KOMMUN_ID NUMBER
                GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            KOMMUN_NAME VARCHAR2(100 CHAR) NOT NULL,
            LAN_ID NUMBER NOT NULL,

            CONSTRAINT UQ_KOMMUN_LAN
                UNIQUE (KOMMUN_NAME, LAN_ID),

            CONSTRAINT FK_KOMMUN_LAN
                FOREIGN KEY (LAN_ID)
                REFERENCES LAN(LAN_ID)
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN
            RAISE;
        END IF;
END;
/

MERGE INTO KOMMUN k
USING (
    SELECT DISTINCT
        y.KOMMUN AS KOMMUN_NAME,
        l.LAN_ID
    FROM YH_APPLICATIONS_2025 y
    JOIN LAN l
        ON y.LAN = l.LAN_NAME
    WHERE y.KOMMUN IS NOT NULL
      AND y.KOMMUN <> 'Flera kommuner'
      AND y.LAN <> 'Flera kommuner'
) n
ON (
    k.KOMMUN_NAME = n.KOMMUN_NAME
    AND k.LAN_ID = n.LAN_ID
)
WHEN NOT MATCHED THEN
    INSERT (KOMMUN_NAME, LAN_ID)
    VALUES (n.KOMMUN_NAME, n.LAN_ID);

COMMIT;

SELECT COUNT(*) AS ANTAL_KOMMUNER
FROM KOMMUN;

SELECT
    k.KOMMUN_ID,
    k.KOMMUN_NAME,
    l.LAN_NAME
FROM KOMMUN k
JOIN LAN l
    ON k.LAN_ID = l.LAN_ID
ORDER BY k.KOMMUN_NAME;
