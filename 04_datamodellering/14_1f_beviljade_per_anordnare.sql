-- Antal beviljade ansokningar per utbildningsanordnare
-- och utbildningsnamn inom Data/IT
SELECT
    ua.NAMN AS UTBILDNINGSANORDNARE,
    a.UTBILDNINGSNAMN,
    COUNT(*) AS ANTAL_BEVILJADE
FROM ANSOKAN a
JOIN UTBILDNINGSANORDNARE ua
    ON a.ANORDNARE_ID = ua.ANORDNARE_ID
JOIN SUN5_INRIKTNING s
    ON a.SUN5_KOD = s.SUN5_KOD
JOIN UTBILDNINGSOMRADE u
    ON s.UTBILDNINGSOMRADE_ID = u.UTBILDNINGSOMRADE_ID
WHERE u.UTBILDNINGSOMRADE_NAME = 'Data/IT'
  AND a.BESLUT = 'Beviljad'
GROUP BY
    ua.NAMN,
    a.UTBILDNINGSNAMN
ORDER BY
    ANTAL_BEVILJADE DESC,
    ua.NAMN,
    a.UTBILDNINGSNAMN;
