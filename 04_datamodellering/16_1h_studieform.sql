-- Andel distans och bunden per utbildningsomrade
-- Nya datamodellen med JOIN

SELECT
    u.UTBILDNINGSOMRADE_NAME AS UTBILDNINGSOMRADE,
    a.STUDIEFORM,
    COUNT(*) AS ANTAL_ANSOKNINGAR,
    ROUND(
        100 * COUNT(*) /
        SUM(COUNT(*)) OVER (
            PARTITION BY u.UTBILDNINGSOMRADE_NAME
        ),
        2
    ) AS ANDEL_PROCENT
FROM ANSOKAN a
JOIN SUN5_INRIKTNING s
    ON a.SUN5_KOD = s.SUN5_KOD
JOIN UTBILDNINGSOMRADE u
    ON s.UTBILDNINGSOMRADE_ID = u.UTBILDNINGSOMRADE_ID
GROUP BY
    u.UTBILDNINGSOMRADE_NAME,
    a.STUDIEFORM
ORDER BY
    u.UTBILDNINGSOMRADE_NAME,
    a.STUDIEFORM;
